"""Record pip-parseable versions from the acceptance experiment environment.

This is a partial lock, not a promise that every optional package is present.
Unconfirmed optional packages are documented separately rather than emitted
as invalid requirements.
"""

import argparse
import importlib.metadata as metadata
import json
import os
import platform
import sys

if hasattr(sys.stdout, "reconfigure"):
    sys.stdout.reconfigure(encoding="utf-8")

PACKAGES = [
    "sentence-transformers",
    "faiss-cpu",
    "rank-bm25",
    "langchain-core",
    "openai",
    "brotlicffi",
    "python-docx",
    "pandas",
    "matplotlib",
    "gradio",
    "numpy",
    "torch",
    "transformers",
    "tokenizers",
    "huggingface-hub",
    "httpx",
    "httpx2",
    "pypdf",
    # Optional PDF utility. It is kept in the status snapshot so its absence is
    # explicit; PDF verification uses the bundled PDF runtime instead.
]


def collect():
    versions = {}
    for name in PACKAGES:
        try:
            versions[name] = metadata.version(name)
        except metadata.PackageNotFoundError:
            versions[name] = None
    return {
        "status": "PARTIAL",
        "reason": (
            "Versions are recorded from the environment used for the acceptance "
            "repair. Optional packages that are not installed are documented as "
            "not_installed_optional rather than emitted as placeholder pins."
        ),
        "python": {
            "version": platform.python_version(),
            "implementation": platform.python_implementation(),
            "executable_name": os.path.basename(sys.executable),
        },
        "packages": versions,
        "not_installed_optional": [
            name for name, version in versions.items() if version is None
        ],
        "available": [name for name, version in versions.items() if version is not None],
        "optional_packages": {
            "brotlicffi": (
                "Not installed. openai 3.36.0 depends on httpx2>=2.12; "
                "httpx2 declares brotlicffi only for the optional 'brotli' extra "
                "on non-CPython runtimes. This acceptance environment is CPython "
                "3.10 and the project's OpenAI call does not request br decoding, "
                "so it is not a runtime requirement here. Do not install it as a "
                "stand-in for the project's historical httpx1 constraint."
            ),
            "pypdf": (
                "Optional PDF utility, not a runtime dependency of the DOCX corpus. "
                "The delivery PDF is verified separately with the bundled PDF tools."
            ),
        },
    }


def render(report):
    lines = [
        "# Delivery dependency snapshot (PARTIAL)",
        f"# Generated by scripts/write_delivery_requirements_lock.py",
        f"# Python {report['python']['version']} "
        f"({report['python']['implementation']})",
        "#",
        "# This is a partial, pip-parseable snapshot, not a hermetic lock.",
        "# Only packages confirmed by importlib.metadata are pinned below.",
        "# Optional/unconfirmed packages are documented in status JSON and",
        "# comments; invalid placeholder requirements are never emitted.",
    ]
    for name, version in report["packages"].items():
        if version is None:
            continue
        lines.append(f"{name}=={version}")
    lines.append("")
    lines.append("# Status: PARTIAL")
    lines.append("# Unconfirmed in this environment: "
        + (", ".join(report["not_installed_optional"]) or "none"))
    lines.append("# openai==3.36.0 uses httpx2 (not httpx) for transport; "
                 "both observed versions are pinned when available.")
    lines.append("# brotlicffi: optional non-CPython 'brotli' extra of httpx2; "
                 "not required by this CPython 3.10 OpenAI call path.")
    lines.append("# pypdf: optional PDF utility; the corpus is DOCX and the "
                 "delivery PDF is checked separately.")
    lines.append("# Experimental reproduction must install the project's declared"
                 " dependencies and preserve the result hashes.")
    return "\n".join(lines) + "\n"


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--out", default=os.path.join(
        "repair_outputs", "acceptance_20261023", "delivery", "requirements-lock.txt"))
    parser.add_argument("--json-out", default=os.path.join(
        "repair_outputs", "acceptance_20261023", "delivery",
        "requirements-lock-status.json"))
    args = parser.parse_args()
    report = collect()
    os.makedirs(os.path.dirname(os.path.abspath(args.out)), exist_ok=True)
    with open(args.out, "w", encoding="utf-8", newline="\n") as handle:
        handle.write(render(report))
    with open(args.json_out, "w", encoding="utf-8") as handle:
        json.dump(report, handle, ensure_ascii=False, indent=2)
        handle.write("\n")
    print(f"[lock] {report['status']}: {os.path.abspath(args.out)}")
    print(
        "[lock] not_installed_optional: "
        + (", ".join(report["not_installed_optional"]) or "none")
    )


if __name__ == "__main__":
    main()
